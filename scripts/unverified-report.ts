import { ERA_BINS } from '../src/data/catalog.ts';
import { toT } from '../src/lib/years.ts';
import type { ClimateCurve, Dataset, Verification } from '../src/data/schema/index.ts';

export const REPORT_KINDS = [
  'polities',
  'relations',
  'callouts',
  'bands',
  'routes',
  'tour stops',
  'climate',
] as const;

export type ReportKind = (typeof REPORT_KINDS)[number];

const STATUSES = ['unverified', 'cross-checked', 'primary-checked'] as const;

const ERA_KINDS = [
  'polities',
  'callouts',
  'relations',
  'bands',
  'routes',
  'tour stops',
] as const satisfies readonly ReportKind[];

const IMPORTANCE_KINDS = [
  'polities',
  'callouts',
  'bands',
  'routes',
] as const satisfies readonly ReportKind[];

export interface ReportClaim {
  kind: ReportKind;
  id: string;
  verification: Verification;
  importance?: number;
  family?: string;
  start: number;
  end: number;
}

function overlaps(
  start: number,
  end: number,
  eraStart: number,
  eraEnd: number,
): boolean {
  return toT(start) <= toT(eraEnd) && toT(end) >= toT(eraStart);
}

function cell(value: string): string {
  return value.replaceAll('|', '\\|');
}

export function claimsFrom(dataset: Dataset, climate: ClimateCurve): ReportClaim[] {
  const familyOf = new Map(
    dataset.polities.map((polity) => [polity.id, polity.family]),
  );
  const claims: ReportClaim[] = [];
  for (const polity of dataset.polities) {
    claims.push({
      kind: 'polities',
      id: polity.id,
      verification: polity.verification,
      importance: polity.importance,
      family: polity.family,
      start: polity.start,
      end: polity.end,
    });
  }
  for (const relation of dataset.relations) {
    claims.push({
      kind: 'relations',
      id: relation.id,
      verification: relation.verification,
      start: relation.year,
      end: relation.year,
    });
  }
  for (const callout of dataset.callouts) {
    claims.push({
      kind: 'callouts',
      id: callout.id,
      verification: callout.verification,
      importance: callout.importance,
      family: callout.attachTo ? familyOf.get(callout.attachTo) : undefined,
      start: callout.year,
      end: callout.endYear ?? callout.year,
    });
  }
  for (const band of dataset.bands) {
    claims.push({
      kind: 'bands',
      id: band.id,
      verification: band.verification,
      importance: band.importance,
      start: band.start,
      end: band.end,
    });
  }
  for (const route of dataset.routes) {
    claims.push({
      kind: 'routes',
      id: route.id,
      verification: route.verification,
      importance: route.importance,
      start: route.start,
      end: route.end,
    });
  }
  for (const tour of dataset.tours) {
    tour.waypoints.forEach((stop, index) => {
      claims.push({
        kind: 'tour stops',
        id: `${tour.id}:${index + 1}`,
        verification: stop.verification ?? 'unverified',
        start: stop.year,
        end: stop.year,
      });
    });
  }
  const first = climate.points[0];
  if (!first) throw new Error('climate curve has no points');
  let start = first.year;
  let end = first.year;
  for (const point of climate.points) {
    if (point.year < start) start = point.year;
    if (point.year > end) end = point.year;
  }
  claims.push({
    kind: 'climate',
    id: 'climate',
    verification: climate.verification,
    start,
    end,
  });
  return claims;
}

function statusCount(
  claims: readonly ReportClaim[],
  kind: ReportKind,
  status: Verification,
): number {
  return claims.filter((claim) => claim.kind === kind && claim.verification === status)
    .length;
}

function eraCount(
  claims: readonly ReportClaim[],
  kind: ReportKind,
  eraId: string,
): number {
  const era = ERA_BINS.find((bin) => bin.id === eraId);
  if (!era) return 0;
  return claims.filter(
    (claim) =>
      claim.kind === kind &&
      claim.verification === 'unverified' &&
      overlaps(claim.start, claim.end, era.start, era.end),
  ).length;
}

export function unverifiedMarkdown(
  claims: readonly ReportClaim[],
  familyIds: readonly string[],
): string {
  const lines = [
    '# Unverified claims',
    '',
    'Generated by `npm run report:unverified`. Do not hand-edit.',
    '',
    'A row is unverified when `verification` is `unverified`, or when a tour stop omits the field. Era bins are the §7 bins. A span counts in every bin it overlaps, so a year on a shared edge counts in both bins. The climate curve is one claim and is not spread across bins.',
    '',
    '## Totals',
    '',
    '| kind | unverified | cross-checked | primary-checked | total |',
    '| --- | --- | --- | --- | --- |',
  ];
  for (const kind of REPORT_KINDS) {
    const counts = STATUSES.map((status) => statusCount(claims, kind, status));
    const total = counts.reduce((sum, count) => sum + count, 0);
    lines.push(`| ${kind} | ${counts.join(' | ')} | ${total} |`);
  }

  lines.push(
    '',
    '## By importance',
    '',
    'Counts are unverified / cross-checked / primary-checked.',
    '',
    '| kind | importance | unverified | cross-checked | primary-checked |',
    '| --- | --- | --- | --- | --- |',
  );
  for (const kind of IMPORTANCE_KINDS) {
    for (const importance of [1, 2, 3, 4, 5]) {
      const counts = STATUSES.map(
        (status) =>
          claims.filter(
            (claim) =>
              claim.kind === kind &&
              claim.importance === importance &&
              claim.verification === status,
          ).length,
      );
      lines.push(`| ${kind} | ${importance} | ${counts.join(' | ')} |`);
    }
  }

  const high = claims.filter(
    (claim) => claim.importance !== undefined && claim.importance >= 4,
  );
  const flagged = high
    .filter((claim) => claim.verification === 'unverified')
    .sort(
      (a, b) =>
        REPORT_KINDS.indexOf(a.kind) - REPORT_KINDS.indexOf(b.kind) ||
        a.id.localeCompare(b.id),
    );
  lines.push(
    '',
    '## Importance 4 and 5 still unverified',
    '',
    `importance>=4 unverified: ${flagged.length} of ${high.length}`,
    '',
    'P6 requires every importance ≥ 4 entry to be cross-checked or primary-checked.',
    '',
  );
  if (flagged.length === 0) {
    lines.push('None.');
  } else {
    lines.push('| kind | id | importance |', '| --- | --- | --- |');
    for (const claim of flagged) {
      lines.push(`| ${claim.kind} | ${cell(claim.id)} | ${claim.importance} |`);
    }
  }

  lines.push(
    '',
    '## By era',
    '',
    'Unverified counts only.',
    '',
    `| era | ${ERA_KINDS.join(' | ')} |`,
    `| --- | ${ERA_KINDS.map(() => '---').join(' | ')} |`,
  );
  for (const era of ERA_BINS) {
    const counts = ERA_KINDS.map((kind) => eraCount(claims, kind, era.id));
    lines.push(`| ${era.id} | ${counts.join(' | ')} |`);
  }

  const known = new Set(familyIds);
  const extra = [
    ...new Set(
      claims
        .map((claim) => claim.family)
        .filter(
          (family): family is string => family !== undefined && !known.has(family),
        ),
    ),
  ].sort((a, b) => a.localeCompare(b));
  const families = [...familyIds, ...extra];
  const unattached = claims.filter(
    (claim) =>
      claim.kind === 'callouts' && claim.verification === 'unverified' && !claim.family,
  ).length;
  lines.push(
    '',
    '## By family',
    '',
    'Polities use their own family. Callouts use the family of `attachTo`. Relations are not assigned a family.',
    '',
    `Unverified callouts with no family: ${unattached}.`,
    '',
    '| family | unverified polities | unverified callouts |',
    '| --- | --- | --- |',
  );
  for (const family of families) {
    const polities = claims.filter(
      (claim) =>
        claim.kind === 'polities' &&
        claim.family === family &&
        claim.verification === 'unverified',
    ).length;
    const callouts = claims.filter(
      (claim) =>
        claim.kind === 'callouts' &&
        claim.family === family &&
        claim.verification === 'unverified',
    ).length;
    lines.push(`| ${cell(family)} | ${polities} | ${callouts} |`);
  }

  lines.push(
    '',
    'Notes, presets, media, and sources have no `verification` field, so they are not counted.',
    '',
  );
  return lines.join('\n');
}
