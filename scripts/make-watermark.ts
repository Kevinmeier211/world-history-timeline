import { writeFileSync } from 'node:fs';

import { feature } from 'topojson-client';
import type { GeometryCollection, Topology } from 'topojson-specification';
import land from 'world-atlas/land-110m.json' with { type: 'json' };

import geography from '../src/data/geography.json' with { type: 'json' };
import { posterWorld } from '../src/camera/camera.ts';
import { landPath, watermarkBox } from '../src/render/watermark.ts';

interface LandGeometry {
  type: string;
  coordinates: number[][][][];
}

interface LandCollection {
  features: { geometry: LandGeometry }[];
}

const topology = land as unknown as Topology<{ land: GeometryCollection }>;
const collection = feature(
  topology,
  topology.objects.land,
) as unknown as LandCollection;
const geometry = collection.features[0]?.geometry;
if (!geometry || geometry.type !== 'MultiPolygon') {
  throw new Error('world-atlas land is not a multipolygon');
}

function toPolygons(
  coordinates: number[][][][],
): readonly (readonly (readonly [number, number])[])[][] {
  return coordinates.map((polygon) =>
    polygon.map((ring) =>
      ring.flatMap((point) => {
        const lon = point[0];
        const lat = point[1];
        if (lon === undefined || lat === undefined) return [];
        return [[lon, lat] as const];
      }),
    ),
  );
}

const box = watermarkBox(posterWorld().height);
const d = landPath(toPolygons(geometry.coordinates), geography.knots, box);
if (!d.startsWith('M')) throw new Error('watermark path is empty');

const svg = [
  '<?xml version="1.0" encoding="UTF-8"?>',
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="${box.x} ${box.y} ${box.width} ${box.height}" fill="currentColor">`,
  `  <path d="${d}"/>`,
  '</svg>',
  '',
].join('\n');

writeFileSync('public/watermark.svg', svg);
writeFileSync(
  'src/render/watermark.generated.ts',
  `/* Generated by scripts/make-watermark.ts. Do not edit. */\nexport const watermarkD = ${JSON.stringify(d)};\n`,
);

console.log(
  `watermark: ${geometry.coordinates.length} polygons, ${d.length} chars, box ${box.width.toFixed(0)}×${box.height.toFixed(0)}`,
);
