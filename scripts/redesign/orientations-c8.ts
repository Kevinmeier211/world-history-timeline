const ref = (source: string, locator: string) => ({ source, locator });
const s = (
  title: string,
  text: string,
  ...citations: Section['citations']
): Section => ({ title, text, citations });
const snap = (year: number, text: string, ...citations: Section['citations']) => ({
  year,
  text,
  citations,
});
function reading(
  n: number,
  region: Region,
  title: string,
  question: string,
  sections: Section[],
  scope: string,
  perspectives: string,
  contextIds: string[],
  subjectIds: string[],
  prompt: string,
  response: string,
  dates: ReturnType<typeof snap>[],
): RegionalOrientation {
  const id = `C8-R${n}`;
  return {
    id,
    chapter: 'C8',
    region,
    title,
    question,
    summary: sections[0]!,
    sections: sections.slice(1),
    scope,
    perspectives,
    contextIds,
    subjectIds,
    activity: { prompt, response },
    snapshots: dates.map((date) => ({ orientation: id, region, ...date })),
  };
}
