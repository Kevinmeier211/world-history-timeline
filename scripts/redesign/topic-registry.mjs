import fs from 'node:fs/promises';
import assert from 'node:assert/strict';
import { format, resolveConfig } from 'prettier';

const formatting = await resolveConfig('docs/redesign/TOPIC-REGISTRY.json');

const corpus = JSON.parse(await fs.readFile('public/atlas/corpus.json', 'utf8'));
const plan = JSON.parse(await fs.readFile('docs/redesign/topic-plan.json', 'utf8'));
const ids = plan.rows.map((row) => row[0]);
assert.equal(new Set(ids).size, ids.length, 'Duplicate editorial plan ID');
assert.deepEqual(
  [...ids].sort(),
  corpus.subjects.map((s) => s.id).sort(),
  'Topic registry must account for every current dossier exactly once',
);
const registry = plan.rows.map(
  ([id, currentRole, action, referenceDestination, nextEditorialTask]) => {
    const s = corpus.subjects.find((row) => row.id === id);
    const contexts = (corpus.contexts ?? []).filter((c) =>
      s.contextIds?.includes(c.id),
    );
    const refs = [
      ...s.sections,
      ...(s.deeperReading ?? []),
      ...(s.evidenceReading?.items ?? []),
      ...s.claims,
      ...Object.values(s.dimensions),
      ...(s.placeStudy?.points ?? []),
      ...(s.placeStudy?.features ?? []),
      ...contexts,
      ...contexts.flatMap((c) => c.phases),
    ].flatMap((row) => row.citations ?? []);
    const media = corpus.media.filter((m) => s.objectIds.includes(m.id));
    const sourceIds = [
      ...new Set([
        ...refs.map((r) => r.source),
        ...media.map((m) => m.source),
        ...media.flatMap(
          (m) =>
            m.annotations?.items.flatMap((note) =>
              note.citations.map((r) => r.source),
            ) ?? [],
        ),
      ]),
    ];
    const words = (text) => text.trim().split(/\s+/).filter(Boolean).length;
    return {
      id,
      name: s.name,
      packs: s.packs,
      region: s.region,
      currentRole,
      action,
      referenceDestination,
      nextEditorialTask,
      question: s.question,
      caseInterval: s.interval,
      geographicPrecision: s.geographicPrecision,
      contexts: contexts.map((c) => ({
        id: c.id,
        title: c.title,
        interval: c.interval,
      })),
      mainWords: words([s.summary, ...s.sections.map((x) => x.text)].join(' ')),
      deeperWords: words((s.deeperReading ?? []).map((x) => x.text).join(' ')),
      images: media.map((m) => ({
        id: m.id,
        depiction: m.depiction,
        rights: m.rights,
        source: m.source,
      })),
      sourceScopes: sourceIds.map((id) => {
        const source = corpus.sources.find((x) => x.id === id);
        assert.ok(source, 'Unknown registry source: ' + id);
        return { id, url: source.url, accessed: source.accessed, scope: source.scope };
      }),
      learningPaths: corpus.journeys
        .filter((j) => j.stops.some((stop) => stop.subject === id))
        .map((j) => j.id),
      review: s.review ?? {
        scope:
          'No expanded-layer review record. Existing citations and claim checks remain; registry compilation is not renewed verification.',
      },
    };
  },
);
await fs.writeFile(
  'docs/redesign/TOPIC-REGISTRY.json',
  await format(
    JSON.stringify({ version: plan.version, scope: plan.scope, dossiers: registry }),
    { ...formatting, parser: 'json' },
  ),
);
const expanded = corpus.subjects.filter(
  (s) => s.deeperReading && s.contextIds?.length,
).length;
const pending = corpus.subjects.length - expanded;
const pendingSentence =
  pending === 1
    ? '1 other still needs the planned assessment or work below.'
    : `${pending} others still need the planned assessment or work below.`;
const lines = [
  '# Current topic registry',
  '',
  'Current implementation and acceptance status: [completion tracker](COMPLETION-TRACKER-2026-11-04.json) and [generated inventory](CURRENT-STATE.json). This registry is editorial routing evidence, not a record of independent approval.',
  '',
  plan.scope,
  '',
  'The authoring plan is in [topic-plan.json](topic-plan.json). The [full registry](TOPIC-REGISTRY.json) records every current date explanation, source scope/access note, image right, reference context, reading length and learning-path membership. It is regenerated by content:build. Word counts are diagnostics, not quality thresholds.',
  '',
  '**Role:** “case + reference” means a bounded reference frame is present, not an accepted comprehensive history. “Review” means the local expansion needs editorial/human assessment. “Keep” preserves a useful small inquiry; “connect” adds a reference destination; “deepen” adds explanation; “split” separates an overbroad label from its evidence case. None authorizes automatic rewriting or publication.',
  '',
  `${registry.length} stable dossiers are accounted for. ${expanded} have expanded reading and reference layers. ${pendingSentence} Broad topic destinations are proposed research scopes, not already sourced entries or exact historical lifetimes.`,
  '',
];
for (const pack of corpus.packs) {
  const rows = registry.filter((r) => r.packs[0] === pack.id);
  lines.push(
    '## ' + pack.id + ' · ' + pack.title,
    '',
    '| Dossier / current role | Action and destination | Specific next work |',
    '|---|---|---|',
  );
  for (const r of rows)
    lines.push(
      '| ' +
        r.id +
        ' · ' +
        r.currentRole +
        ' | ' +
        r.action +
        ': ' +
        r.referenceDestination +
        ' | ' +
        r.nextEditorialTask +
        ' |',
    );
  lines.push('');
}
lines.push(
  '## Finite expansion order',
  '',
  'This registry covers the existing atlas and the two newly authorized additions. It does not attempt to name every society. Author one bounded workpack at a time; preserve the case IDs and date explanations when adding reference frames.',
  '',
  '| Workpack | Next bounded scope | Required output before expansion |',
  '|---|---|---|',
  '| C8 current | Indonesia, Ghana, South Africa, linked to Partition | Local accounts, documents/images, three place studies, dated phases and learning path; human/editorial review remains |',
  '| C1 local candidate | Uruk, Dholavira and Liangzhu urban work | Three expanded accounts, distinct reference frames, original sourced diagrams and a focused inquiry; household detail, full plan/figure review and independent/human acceptance remain |',
  '| C2 local candidate | Hattusha, Uluburun and Shang | Three expanded accounts, separate reference frames, original evidence diagrams, an inspected gong photograph and a focused inquiry; household/workshop detail, disputed metal origins and independent/human acceptance remain |',
  '| C3 local candidate | Qin, Ashoka and Athens | Three expanded accounts, phased reference frames, three geographic studies, two original diagrams and a focused inquiry; legal/linguistic review, wider social evidence and independent/human acceptance remain |',
  '| C4 local candidate | Palmyra, Kushan and Aksum | Three expanded accounts, separate reference phases, three geographic studies, an excavated coin photograph and a focused inquiry; local-language/numismatic, household and independent/human review remain |',
  '| C5 local candidate | Tang/Chang’an, Abbasid Iraq and Nalanda | Three expanded accounts, distinct reference phases and geography, two original diagrams, a licensed ruins photograph and focused inquiry; original legal/land records, wider social histories and independent/human review remain |',
  '| C5 | Tang, Abbasid Iraq and Nalanda | Urban institutions, learning and work; phase-aware reference entries and plans |',
  '| C6 | Mali, Cahokia and Inca contexts | Work and political organization, community/situated sources, regional chronology and explanatory geography |',
  '| C7 | Kongo, Banda and Isfahan/New Julfa | Translation, coercion and exchange; locally situated voices, dated routes and urban/island maps |',
  '| C8 next | Haiti, Tomioka and Cold War contexts | Strengthen labor/production and modern institutions; do not represent 1950 as a complete world snapshot |',
  '',
  'Across all workpacks, revisit the preserved small-object and community cases through their listed destinations. New dossiers outside this finite list require a stated scope, sources and a coverage rationale; the legacy disposition ledger is a backlog, not verified content.',
  '',
  '## Explicit coverage limits',
  '',
  'The current selection still lacks adequate frameworks for much of Africa, South and Southeast Asia, Oceania and the Americas across long periods; modern East Asia, Latin America, the Middle East, women’s histories and histories of ordinary institutions also need deliberate expansion. These are planning gaps, not empty places on the historical map. The workpack order is a manageable next sequence, not a claim that the remaining globe is complete.',
  '',
  'UI/UX, notebook revision, glossary at the point of need, richer exercises, graphic explanation, broader reference coverage, print redesign, portable packaging and independent/human acceptance remain in the [roadmap](ROADMAP-2026-10-27.md). The registry complements that plan; it does not replace its engineering and design requirements.',
  '',
);
await fs.writeFile(
  'docs/redesign/TOPIC-REGISTRY.md',
  await format(lines.join('\n'), { ...formatting, parser: 'markdown' }),
);
